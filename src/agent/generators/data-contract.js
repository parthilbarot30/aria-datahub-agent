import Groq from 'groq-sdk';

const groq = new Groq({ apiKey: process.env.GROQ_API_KEY });

const claude = {
  messages: {
    create: async ({ model, max_tokens, system, messages }) => {
      const msgs = system
        ? [{ role: 'system', content: system }, ...messages]
        : messages;
      const res = await groq.chat.completions.create({
        model: model || 'llama-3.3-70b-versatile',
        max_tokens,
        messages: msgs,
      });
      return {
        content: [{ text: res.choices[0].message.content }]
      };
    }
  }
};

export async function generateDataContract(diagnosis, context, assetInfo) {
  const upstreamSource = context.upstream[0];
  const sourceFields = upstreamSource?.entity?.schemaMetadata?.fields || [];

  const prompt = `You are a data reliability engineer writing a DataHub data contract.

INCIDENT SUMMARY:
- Broken asset: ${assetInfo.assetName}  
- Breaking source: ${diagnosis.breakingChangeSource}
- Breaking change: ${diagnosis.breakingChangeType}
- Prevention gap: ${diagnosis.preventionGap}

UPSTREAM SCHEMA (current, from DataHub):
${sourceFields.map(f => `- ${f.fieldPath}: ${f.type}${f.nullable ? ' (nullable)' : ' (required)'}`).join('\n')}

Generate a DataHub data contract YAML that would have PREVENTED this incident.
Include schema assertions for critical columns, a freshness SLA, and at least one data quality check.

Respond ONLY with valid YAML. No markdown code fences, no explanation before or after.`;

  const res = await claude.messages.create({
    model: 'llama-3.3-70b-versatile',
    max_tokens: 800,
    messages: [{ role: 'user', content: prompt }],
  });

  const rawYaml = res.content[0].text.replace(/```yaml|```/g, '').trim();

  if (!rawYaml.includes(':')) {
    return generateDefaultContract(assetInfo, upstreamSource, diagnosis);
  }

  return rawYaml;
}

function generateDefaultContract(assetInfo, upstreamSource, diagnosis) {
  const sourceName = upstreamSource?.entity?.name || 'source_table';
  const fields = upstreamSource?.entity?.schemaMetadata?.fields?.slice(0, 5) || [];

  return `# DataHub Data Contract
# Generated by ARIA — ${new Date().toISOString()}
# This contract would have caught: ${diagnosis.breakingChangeType}

id: "contract-${assetInfo.assetName}-upstream"
version: "1.0"
entity: "${sourceName}"

schema:
  assertions:
${fields.map(f => `    - column: "${f.fieldPath}"
      required: true
      type: "${f.type}"`).join('\n')}

freshness:
  assertions:
    - maxAge: "PT24H"
      description: "Source data must be updated at least once per day"

quality:
  assertions:
    - sql: "SELECT COUNT(*) FROM ${sourceName} WHERE ${fields[0]?.fieldPath || 'id'} IS NULL"
      operator: EQUAL_TO
      value: 0
      description: "Primary key must never be null"

contact:
  owners:
    - team: "data-engineering"
  slack: "#data-incidents"
  onViolation: PAGE_OWNER
`;
}